# occt_edge_map.py — FreeCAD unit-box edges + AZRA (face,edge) map by midpoint
# Run: freecadcmd -c "import runpy; runpy.run_path(r'.../occt_edge_map.py', run_name='__main__')"
#
# AZRA is Y-up centered [-0.5,0.5]^3. FreeCAD makeBox is Z-up [0,1]^3.
# Transform AZRA→OCCT: (x,y,z) → (x+0.5, z+0.5, y+0.5)
# Match edges by midpoint only — never trust raw FreeCAD index == AZRA index.

import json
import os

import FreeCAD
import Part

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "refs")
os.makedirs(OUT, exist_ok=True)

# AZRA unit cube solid edges (hx=hy=hz=0.5), precomputed midpoints in AZRA frame
# Regenerated by: cargo test -p core_math edge_index_map -- --nocapture
# face, edge, mid_azra, mid_occt (via Y-up→Z-up map)
AZRA_EDGES = [
    # filled at runtime from FreeCAD only; AZRA side lives in Rust.
]


def occt_from_azra(x, y, z):
    return [x + 0.5, z + 0.5, y + 0.5]


def azra_from_occt(x, y, z):
    return [x - 0.5, z - 0.5, y - 0.5]


def main():
    box = Part.makeBox(1, 1, 1)
    edges = []
    for i, e in enumerate(box.Edges):
        a = e.Vertexes[0].Point
        b = e.Vertexes[1].Point
        mid = [(a.x + b.x) * 0.5, (a.y + b.y) * 0.5, (a.z + b.z) * 0.5]
        edges.append(
            {
                "freecad_i": i,
                "a": [round(a.x, 6), round(a.y, 6), round(a.z, 6)],
                "b": [round(b.x, 6), round(b.y, 6), round(b.z, 6)],
                "mid_occt": [round(m, 6) for m in mid],
                "mid_azra": [round(v, 6) for v in azra_from_occt(*mid)],
            }
        )
        print(
            "FC",
            i,
            "mid_occt",
            edges[-1]["mid_occt"],
            "mid_azra",
            edges[-1]["mid_azra"],
        )

    top = [e for e in edges if abs(e["a"][2] - 1) < 1e-9 and abs(e["b"][2] - 1) < 1e-9]
    corner_111 = [
        e
        for e in edges
        if any(
            abs(p[0] - 1) < 1e-9 and abs(p[1] - 1) < 1e-9 and abs(p[2] - 1) < 1e-9
            for p in (e["a"], e["b"])
        )
    ]

    payload = {
        "note": "Match FreeCAD edges to AZRA via mid_occt / mid_azra. Never use freecad_i as AZRA index.",
        "transform": {
            "azra_to_occt": "(x,y,z)_azra -> (x+0.5, z+0.5, y+0.5)_occt  # Y-up to Z-up",
            "occt_to_azra": "(x,y,z)_occt -> (x-0.5, z-0.5, y-0.5)_azra",
        },
        "freecad_version": ".".join(str(x) for x in FreeCAD.Version()[:3]),
        "edges": edges,
        "presets": {
            "top_loop_freecad_i": [e["freecad_i"] for e in top],
            "top_loop_mids_occt": [e["mid_occt"] for e in top],
            "corner_111_freecad_i": [e["freecad_i"] for e in corner_111],
            "corner_111_mids_occt": [e["mid_occt"] for e in corner_111],
            "single_top_edge5_mid_occt": [1.0, 0.5, 1.0],
        },
    }
    path = os.path.join(OUT, "edge_map_unit_box_corrected.json")
    with open(path, "w", encoding="utf-8") as fp:
        json.dump(payload, fp, indent=1)
    print("wrote", path)
    print("top_loop FC", payload["presets"]["top_loop_freecad_i"])
    print("corner_111 FC", payload["presets"]["corner_111_freecad_i"])


if __name__ == "__main__":
    main()
